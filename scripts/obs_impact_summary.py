#!/usr/bin/env python3
"""Combine trusted local per-cycle summary pickles into one aligned text file."""
import argparse
from datetime import datetime
import math
import os
from pathlib import Path
import pickle
import tempfile

FIELDS = ('omb_min', 'omb_mean', 'omb_max',
          'oma_min', 'oma_mean', 'oma_max')


def summarize(cycle, pickle_dir, output_dir, groups=('conv', 'conv_uv', 'sate')):
    """Read all required groups before atomically publishing the cycle text."""
    if len(cycle) != 10 or not cycle.isdigit():
        raise ValueError('cycle must be YYYYMMDDHH')
    datetime.strptime(cycle, '%Y%m%d%H')
    if not groups or len(groups) != len(set(groups)) or set(groups) - {'conv', 'conv_uv', 'sate'}:
        raise ValueError('groups must be a unique selection of conv,conv_uv,sate')
    rows = []
    seen = set()
    for group in groups:
        source = Path(pickle_dir) / f'{cycle}_{group}.pkl'
        print(f'[READ] Summary pickle: {source}', flush=True)
        # Only load pickles generated by these processors in a trusted directory.
        with source.open('rb') as stream:
            record = pickle.load(stream)
        if not isinstance(record, (tuple, list)) or len(record) not in (6, 7):
            raise ValueError(f'{source}: expected six summary arrays with optional departure metadata')
        sensors, totals, counts, means, impacts, maxima = record[:6]
        metadata = record[6] if len(record) == 7 else {}
        if not isinstance(metadata, dict):
            raise ValueError(f'{source}: invalid metadata')
        departures = metadata.get('departure_stats', {})
        if not isinstance(departures, dict):
            raise ValueError(f'{source}: invalid departure_stats')
        if not departures:
            print(f'[WARN] {source}: no departure statistics; rerun processors to populate them', flush=True)
        if any(len(array) != len(sensors) for array in record[1:6]):
            raise ValueError(f'{source}: inconsistent summary array lengths')
        for sensor, impact, count in zip(sensors, impacts, counts):
            sensor = str(sensor)
            if not sensor or any(c.isspace() for c in sensor) or sensor.startswith('#'):
                raise ValueError(f'{source}: invalid data type {sensor!r}')
            if sensor in seen:
                raise ValueError(f'{source}: duplicate output type {sensor}')
            seen.add(sensor)
            impact, count = float(impact), float(count)
            if math.isnan(impact):
                print(f'[WARN] {sensor}: NaN impact written as 0', flush=True)
                impact = 0.0
            if not math.isfinite(impact):
                raise ValueError(f'{source}: infinite impact for {sensor}')
            if not math.isfinite(count) or count < 0 or not count.is_integer():
                raise ValueError(f'{source}: invalid observation count for {sensor}')
            stats = departures.get(sensor, {})
            values = [float(stats.get(field, math.nan)) for field in FIELDS]
            if any(math.isinf(value) for value in values):
                raise ValueError(f'{source}: infinite departure statistic for {sensor}')
            rows.append((sensor, impact, int(count), values))
    # Fixed-width fields, with enough space for every value and header.
    labels = ['data_type', 'total_impact', 'data_count', *FIELDS]
    formatted = [(sensor, f'{impact:.4f}', str(count), *(f'{v:.6f}' for v in stats))
                 for sensor, impact, count, stats in rows]
    widths = [max(minimum, len(label), *(len(row[i]) for row in formatted))
              for i, (minimum, label) in enumerate(zip((24, 16, 12, *([16]*6)), labels))]
    destination = Path(output_dir) / f'{cycle}.txt'
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', dir=destination.parent,
                                         prefix=destination.name + '.', delete=False) as stream:
            temporary = stream.name
            def line(values):
                return f'{values[0]:<{widths[0]}} ' + ' '.join(
                    f'{value:>{width}}' for value, width in zip(values[1:], widths[1:]))
            stream.write('# ' + line(labels) + '\n')
            for row in formatted:
                stream.write('  ' + line(row) + '\n')
            os.fchmod(stream.fileno(), 0o644)
        os.replace(temporary, destination)
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)
    print(f'[SAVE] Combined summary: {destination} ({len(rows)} rows)', flush=True)
    return destination


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cycle', help='UTC YYYYMMDDHH')
    parser.add_argument('--pickle-dir', required=True)
    parser.add_argument('--output-dir', required=True)
    parser.add_argument('--groups', default='conv,conv_uv,sate')
    args = parser.parse_args()
    try:
        summarize(args.cycle, args.pickle_dir, args.output_dir, args.groups.split(','))
    except (OSError, ValueError, TypeError, EOFError, pickle.UnpicklingError) as exc:
        parser.exit(1, f'ERROR: {exc}\n')
